/*---------------------------------------------------------------------------------------------
 *  16 字符 hex ID 生成器（对齐 Mindvas genId）
 *--------------------------------------------------------------------------------------------*/

/** 生成 16 位 hex 随机 ID */
export function genId(): string {
	return Array.from({ length: 16 }, () =>
		Math.floor(Math.random() * 16).toString(16)
	).join('');
}
