// @ts-check
/**
 * Generate a curated shiki entry that replaces the full `shiki` package in the
 * kbblocks webview bundle (IIFE single-file => all `bundledLanguagesInfo`
 * dynamic imports are inlined, pulling every grammar ~7.7 MB).
 *
 * We keep the core APIs BlockSuite needs (createHighlighterCore / codeToTokensBase
 * / codeToHast) and a curated subset of languages. Languages outside the allow
 * list simply disappear from the code-block language dropdown (no runtime errors).
 *
 * Run: node scripts/gen-shiki-curated.mjs
 */
import { writeFile } from 'fs/promises';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
import { bundledLanguagesInfo } from 'shiki';

const __dirname = dirname(fileURLToPath(import.meta.url));

// Canonical shiki lang ids we want bundled. Anything not present in
// `bundledLanguagesInfo` is silently skipped, so this list can be generous.
// Focused on mainstream programming + markup + config languages.
//
// Phase 5 prune (kbblocks bundle was ~7.5 MB, @shikijs/langs accounted for
// ~3.0 MB / 40% of the output): we dropped the single heaviest grammar family
// `cpp` + `cpp-macro` (≈681 KB bundled), the niche `mdx` (≈137 KB), and a set
// of small/esoteric grammars (haskell/elixir/erlang/clojure/ocaml/fsharp/
// matlab/julia/r/perl/scala/dart/lua) that are very unlikely in a developer
// knowledge-base. Missing grammars only disappear from the code-block language
// dropdown — BlockSuite degrades gracefully (no runtime error). To re-add a
// language, just put its id back in ALLOW and re-run this generator.
const ALLOW = new Set([
	'javascript', 'typescript', 'jsx', 'tsx', 'json', 'jsonc',
	'html', 'css', 'scss',
	'markdown',
	'yaml', 'toml', 'ini', 'xml',
	'python', 'shellscript', 'powershell',
	'go', 'rust', 'c', 'csharp', 'java', 'kotlin', 'swift', 'ruby', 'php',
	'sql',
	'vue', 'svelte',
	'docker', 'diff', 'latex', 'graphql',
]);

const curated = bundledLanguagesInfo.filter((info) => ALLOW.has(info.id));
const keptIds = new Set(curated.map((i) => i.id));

// Report any allow-list ids that don't exist in this shiki version.
const missing = [...ALLOW].filter((id) => !keptIds.has(id));
if (missing.length) {
	console.warn(`[shiki-curated] allow-list ids not found in shiki: ${missing.join(', ')}`);
}
console.log(`[shiki-curated] curated ${curated.length} languages (from ${bundledLanguagesInfo.length} total).`);

const entries = curated
	.map((info) => {
		const aliases = info.aliases && info.aliases.length ? `, aliases: ${JSON.stringify(info.aliases)}` : '';
		return `  { id: ${JSON.stringify(info.id)}, name: ${JSON.stringify(info.name)}${aliases}, import: () => import('@shikijs/langs/${info.id}') },`;
	})
	.join('\n');

const out = `// @ts-nocheck
// AUTO-GENERATED by scripts/gen-shiki-curated.mjs — DO NOT EDIT BY HAND.
// Replaces the full 'shiki' package in the kbblocks IIFE bundle so only a curated
// set of language grammars (not all ~200) gets inlined.
import { createHighlighterCore as __createHighlighterCore } from 'shiki/core';
import { createJavaScriptRegexEngine } from '@shikijs/engine-javascript';
export { codeToTokensBase, codeToHast } from 'shiki/core';

// BlockSuite's code-block-service calls:
//   import getWasm from 'shiki/wasm';
//   createHighlighterCore({ loadWasm: getWasm });
// The oniguruma wasm is ~623 KB. We strip \`loadWasm\` here and inject the pure-JS
// regex engine instead, which lets us stub out \`shiki/wasm\` in the esbuild config
// (see shikiWasmStubPlugin). \`forgiving: true\` keeps unsupported grammar regexes
// from throwing at runtime (they are skipped instead of highlighted).
export function createHighlighterCore(options = {}) {
  const { loadWasm, engine, ...rest } = options;
  return __createHighlighterCore({
    ...rest,
    engine: engine ?? createJavaScriptRegexEngine({ forgiving: true }),
  });
}

export const bundledLanguagesInfo = [
${entries}
];
`;

const target = resolve(__dirname, '../src/shiki-curated.ts');
await writeFile(target, out, 'utf8');
console.log(`[shiki-curated] wrote ${target}`);
