/**
 * VsSaros 技能库 → dsh 技能目录（`ctx.skills`）的桥（纯函数，可单测）。
 *
 * dsh 侧机制（0.2.0-rc.2 实测）：
 * - 技能是"目录 + 按需加载"模型——`<available_skills>` 目录进上下文，模型调 `skill` 工具
 *   才加载正文（与 VsSaros 的 activation 主动注入模型不同；auto/always 语义在 dsh 不存在，
 *   技能挂进去后是"目录可见、模型自取"）。
 * - `dsh-skill-filesystem` 支持 `customSkillDirs`；web profile 把宿主层 skill 行禁用了
 *   （preset 各行各自挂本地发现），所以我们插一条**自己的** provider 行（providerName
 *   独立、includeDefaultRoots=false——项目/用户根由 preset 行负责，不重复扫）。
 *
 * 与 MCP 同机制：启动时渲染成 `--patch` 覆盖层，目录增删重启 Host 生效。
 */

/**
 * 渲染技能目录覆盖层；`dirs` 与 `bundledDir` 都为空时只输出注释（调用方此时不应挂覆盖层）。
 *
 * ★ 2026-10-13（P2）：**内置技能改走官方 `bundled` 语义（rank 600）** —— 由 `bundledDir` 单列 ✗ 不再混进
 * `customSkillDirs`（那一档被 `dsh-skill-filesystem` 锁死在 rank 300 ✗，配置里没有 rank/priority 字段 ⇒
 * 改不了）。这样内置的优先级与官方 rank 表一致（用户/项目根都在它之上 ✓），而此前它与用户根同档 300、
 * 只靠数组顺序分先后 ✗。
 *
 * ⚠ `bundledDir` 是**单个**目录（官方 schema 就是 `z.string()`，不是数组 ✗）⇒ 多个内置候选时由调用方挑一个
 * （见 `dshHarnessService._skillDirs` 的注释：dsh 侧内置只有 `FileAccess` 那一个 ✓）。
 */
export function renderSkillsOverlay(dirs: readonly string[], bundledDir?: string): string {
	const lines: string[] = [
		'# Generated by VsSaros for one Host run. Removed when the Host stops.',
		'# Mounts VsSaros skill libraries (builtin resources/.agents/skills + user ~/.vssaros/skills)',
		'# into the dsh skill registry via a dedicated skill-filesystem row.',
	];
	// 与 MCP 覆盖层同约束：只能有一个顶层 `- insert:` 块（多个时加载器只认第一个）。
	//
	// ⚠ 行 id 必须是 **`vssaros-skills-dirs`**，**不能**用 `vssaros-skills`：那一行是
	// `@vssaros/dsh-skills`（本仓的技能模块插件）自己 patch 里插入的行 id ✓。**行 id 就是行身份** ⇒
	// 两行同名时后一份会把前一份**顶掉** ✗（2026-10-12 用 `--patch <本覆盖层> --dump-config` 实测：
	// 组合结果里出现两行同 id，一个 `@vssaros/dsh-skills`、一个 `@deepseek-ai/dsh-skill-filesystem`）——
	// 那样技能模块的页面与 provider 可能整个消失 ✗，而**探针从来看不见**（探针不挂 IDE 这份覆盖层）。
	if (dirs.length || bundledDir) {
		lines.push('- insert:');
		lines.push('    - id: vssaros-skills-dirs');
		lines.push("      name: '@deepseek-ai/dsh-skill-filesystem'");
		lines.push('      config:');
		lines.push("        providerName: 'vssaros'");
		lines.push('        includeDefaultRoots: false');
		lines.push('        watch: true');
		// 空列表就不写这一行（schema 默认 `[]` ✓）；写了空 `[]` 只是噪音
		if (dirs.length) {
			lines.push(`        customSkillDirs: [${dirs.map(yamlScalar).join(', ')}]`);
		}
		if (bundledDir) {
			// rank 600（`BUNDLED_SKILL_RANK`）+ `source: 'bundled'` + `trustedHost: true` —— 依据见
			// `@deepseek-ai/dsh-skill-filesystem/lib/index.js` 的 `bundledSkillDir` 分支 ✓
			lines.push(`        bundledSkillDir: ${yamlScalar(bundledDir)}`);
		}
	}
	lines.push('');
	return lines.join('\n');
}

function yamlScalar(value: string): string {
	// 纯字符串标量一律单引号：路径里的反斜杠、冒号、`#` 都不用特殊处理
	return `'${value.replace(/'/g, '\'\'')}'`;
}
