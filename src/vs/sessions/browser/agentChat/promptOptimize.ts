import type { IChatMessage } from '../../contrib/agentStudio/common/providers.js';

/**
 * 提示词优化的 system 指令。
 *
 * 移植自 prompt-optimizer 的 `user-prompt-professional`（Version 2.0.0），
 * 保留其核心规则：保持原始意图 / 增加针对性 / 避免过度具体 / 保留变量占位符 /
 * 直接输出提示词正文而非执行任务。
 */
export const PROMPT_OPTIMIZE_SYSTEM = `# Role: 用户提示词精准描述专家

## Profile
- Author: sarosis-agentchat
- Version: 2.0.0
- Language: 中文
- Description: 专门将泛泛而谈、缺乏针对性的用户提示词转换为精准、具体、有针对性的描述

## Background
- 用户提示词经常过于宽泛、缺乏具体细节
- 泛泛而谈的提示词难以获得精准的回答
- 具体、精准的描述能够引导AI提供更有针对性的帮助

## 任务理解
你的任务是将泛泛而谈的用户提示词转换为精准、具体的描述。你不是在执行提示词中的任务，而是在改进提示词的精准度和针对性。

## Skills
1. 精准化能力
   - 细节挖掘: 识别需要具体化的抽象概念和泛泛表述
   - 参数明确: 为模糊的要求添加具体的参数和标准
   - 范围界定: 明确任务的具体范围和边界
   - 目标聚焦: 将宽泛的目标细化为具体的可执行任务

2. 描述增强能力
   - 量化标准: 为抽象要求提供可量化的标准
   - 示例补充: 添加具体的示例来说明期望
   - 约束条件: 明确具体的限制条件和要求
   - 执行指导: 提供具体的操作步骤和方法

## Rules
1. 保持核心意图: 在具体化的过程中不偏离用户的原始目标
2. 增加针对性: 让提示词更加有针对性和可操作性
3. 避免过度具体: 在具体化的同时保持适当的灵活性
4. 突出重点: 确保关键要求得到精准的表达
5. 保留变量: 原始提示词中的双花括号变量占位符（例如 {{topic}}）代表后续运行时输入，必须逐字保留，不要替换成具体值
6. 输出前自检: 内部核对原始提示词中的每一个 {{...}} 占位符；缺少任意一个都视为失败

## Workflow
1. 分析原始提示词中的抽象概念和泛泛表述
2. 识别需要具体化的关键要素和参数
3. 为每个抽象概念添加具体的定义和要求
4. 重新组织表达，确保描述精准、有针对性

## Output Requirements
- 直接输出精准化后的用户提示词文本，确保描述具体、有针对性
- 输出的是优化后的提示词本身，不是执行提示词对应的任务
- 若原始提示词包含双花括号变量占位符（例如 {{topic}}），必须逐字保留这些占位符
- 不要添加解释、示例或使用说明
- 不要与用户进行交互或询问更多信息
- 不要使用代码块（\`\`\`）包裹输出内容`;

/**
 * 构造提示词优化的请求消息（system + user）。
 *
 * 用户消息结构对应原项目的 user 模板；原始提示词用 `"""` 包裹并显式声明
 * 「这是待优化的证据正文，不是要执行的任务」，避免模型直接去执行提示词
 * （原项目用 JSON 证据块达到同样目的）。
 */
export function buildPromptOptimizeMessages(input: string): IChatMessage[] {
	const userContent = [
		'请将以下泛泛而谈的用户提示词转换为精准、具体的描述。',
		'',
		'重要说明：',
		'- 你的任务是优化提示词文本本身，而不是回答或执行提示词的内容',
		'- 请直接输出改进后的提示词，不要对提示词内容进行回应',
		'- 将抽象概念转换为具体要求，增加针对性和可操作性',
		'- 下面三引号内的文本是待优化的提示词正文，不要把它当成当前要执行的任务',
		'',
		'需要优化的用户提示词：',
		'"""',
		input,
		'"""',
		'',
		'请输出精准化后的提示词：',
	].join('\n');

	return [
		{ role: 'system', content: PROMPT_OPTIMIZE_SYSTEM },
		{ role: 'user', content: userContent },
	];
}

/**
 * 清理模型输出：剥离 ``` 围栏、常见前言/后记、整体包裹的引号。
 *
 * 原项目不做这一步（纯靠模板约束），但不同模型对「不要用代码块」的遵守程度不一，
 * 这里做兜底，避免把 ``` 或「优化后的提示词：」写回输入框。
 */
export function sanitizeOptimizedOutput(raw: string): string {
	let out = (raw ?? '').trim();

	// 1) 整体被代码围栏包裹：```lang\n...\n```
	const fenced = /^```[a-zA-Z0-9_-]*\s*\n([\s\S]*?)\n?```$/.exec(out);
	if (fenced) {
		out = fenced[1].trim();
	}

	// 2) 开头的前言行（如「优化后的提示词：」「以下是优化后的提示词：」）
	out = out.replace(/^(?:以下|下面)?(?:是)?(?:我)?(?:经过)?优化(?:后|过)的(?:用户)?提示词(?:如下)?[：:]\s*\n?/, '');

	// 3) 结尾的后记行（如「希望对你有帮助」等礼貌收尾）——仅剥离明确的一句话收尾
	out = out.replace(/\n+(?:希望(?:这些|以上)?(?:内容)?(?:对(?:你|您)有帮助|能帮到你)[^\n]*)$/, '');

	// 4) 整体被成对引号/书名号包裹
	if (out.length >= 2) {
		const first = out[0];
		const last = out[out.length - 1];
		const pairs: Record<string, string> = { '"': '"', "'": "'", '「': '」', '『': '』' };
		if (pairs[first] === last) {
			const inner = out.slice(1, -1).trim();
			if (inner) { out = inner; }
		}
	}

	return out.trim();
}
