/** Chat message with streaming/tool-call/thinking support */
export interface IAgentChatMessage {
	readonly id: string;
	readonly role: 'user' | 'assistant' | 'system';
	content: string;
	readonly timestamp: number;
	isStreaming?: boolean;
	/** Precise stream phase (replaces boolean isStreaming for UI display) */
	streamPhase?: StreamPhase;
	/**
	 * 瞬时活动文本（2026-07-26）：tool_progress 等轻量进度信号驱动，
	 * 显示在阶段指示器中（如「正在生成工具调用参数… 已 N KB」）。
	 * 仅流式期间有效，tool_start/done 时清除；不参与持久化语义。
	 */
	activityText?: string;
	/** Hermes turn id — shared by multiple assistant messages from same user request, used for aggregation */
	turnId?: string;
	toolCalls?: IToolCall[];
	/**
	 * 阶段E：有序内容片段（text|tool）。存在时作为渲染唯一真相，
	 * 按数组顺序遍历，取代 textPosition 交织。content/toolCalls 仍保留为派生兼容字段。
	 */
	parts?: IMessagePart[];
	thinking?: string;
	isThinking?: boolean;
	currentStep?: string;           // 'call_llm' | 'execute_tool' | custom
	tokenUsage?: {
		input: number;
		output: number;
		total: number;
		/** KV Cache: tokens read from prompt cache (缓存命中). */
		cached?: number;
		/** KV Cache: tokens written to cache (缓存写入). */
		cacheWrite?: number;
		/** Tokens read from prompt cache (缓存命中, same as cached but explicit). */
		cachedRead?: number;
		/** Tokens NOT in cache that had to be processed fresh (缓存未命中). Computed if not provided. */
		cacheMiss?: number;
		/** Reasoning/thinking tokens (思考过程). */
		reasoning?: number;
		/** Cache hit rate as percentage, e.g. 51.6 for 51.6% (缓存命中率). */
		cacheHitRate?: number;
		/** Billing credits consumed by this turn (积分). */
		credit?: number;
	};
	metadata?: Record<string, unknown>;
	attachments?: IChatAttachment[];
	subAgents?: ISubAgentData[];
	confirmation?: IConfirmationData;
	/** AskUser cards attached to this message (workflow interactive input) */
	askUsers?: ILiveWorkflowAskUser[];
	/** Todo list for task tracking */
	todos?: ITodoItem[];
	/** Plan tasks generated by the plan workflow (plan_exit) — rendered as a dedicated card */
	planTasks?: IPlanTaskCard;
	/** Suggested questions for user to ask */
	questions?: ISuggestedQuestion[];
	/** References used by AI (files, code, etc.) */
	references?: IReferenceItem[];
	/** Tip message (dismissible) */
	tip?: ITipMessage;
	/** Progress messages for tool execution */
	progress?: IProgressMessage[];
	/** LiveWorkflowTraceView: workflow executions attached to this message */
	workflowExecutions?: Record<string, ILiveWorkflowExecution>;
	/** LiveWorkflowTraceView: workflow events timeline */
	workflowEvents?: ILiveWorkflowEvent[];
	/** LiveWorkflowTraceView: collect variables requests */
	collectVariables?: Record<string, ILiveCollectVariable>;
	/** Structured task card data — when set, the renderer builds the task
	 *  prompt card from this data instead of regex-parsing the text content. */
	taskCard?: { title: string; description: string; source?: string; taskId?: string; dependencies?: readonly string[]; attachments?: readonly { name: string; mimeType: string }[] };
}

