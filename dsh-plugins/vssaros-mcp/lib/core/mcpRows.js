// @vssaros/dsh-mcp — 行渲染（纯函数）：把解析后的服务器列表渲染成**组合行 YAML**（每台一行
// `@deepseek-ai/dsh-mcp-client`）。
//
// 为什么插件自己要有这份（2026-10-12，方向调整：MCP 归 dsh 侧）：
//   原先这活儿只在 VsSaros 侧（`src/vs/sessions/contrib/dshHarness/common/dshMcpConfig.ts` 的
//   `renderMcpOverlay`）—— 插件只读、不产生行 ⇒ "配了 MCP 但没壳就挂不上" ✗。现在 dsh 侧也能
//   自己产出同样形状的行（`bin/sync-rows.mjs`），交 loader 的最后一棒可以不由壳来送 ✓。
//
// ⚠ 两份实现**必须逐字节同形**（同样的行 id、同样的缩进、同样只有一个顶层 `- insert:`）——
//   由探针 `poc/dsh-p0/scripts/p3-24-mcp-rows-dsh.mjs` 做**差分**（同一批 fixture 两侧比对）看守 ✓。
//   这不是"重复一份就完事"：差分一红就说明两侧漂移了，别只改一边 ✗。

/** 行 id：`mcp-<serverName>`（与壳侧 `mcpRowId` 同口径，`--dump-config` 里一眼可读）。 */
export function mcpRowId(serverName) {
	return `mcp-${serverName}`;
}

/** YAML 单引号标量：路径里的反斜杠、冒号、`#` 都不用特殊处理（`'` 自身转义成 `''`）。 */
function yamlSingleQuoted(value) {
	return `'${String(value).replace(/'/g, "''")}'`;
}

function yamlScalar(value) {
	return yamlSingleQuoted(value);
}

function yamlInlineList(values) {
	return `[${values.map(yamlScalar).join(', ')}]`;
}

/** 本侧默认头部注释（与壳侧那句**故意不同**：这里不是"一次运行用完即删"的临时覆盖层）。 */
export const DEFAULT_ROWS_HEADER = [
	'# Generated by @vssaros/dsh-mcp (dsh side) from the configured mcp.json.',
	'# dsh-mcp-client is one composition row per server; changing MCP config needs a Host restart.',
];

/**
 * 渲染行体（与壳侧 `renderMcpOverlay` 的**行体**逐字对齐）。
 *
 * ⚠ 只能有**一个**顶层 `- insert:` 块：实测写多个时加载器只认第一个，后面的行**静默消失** ✗
 *（"某台服务器莫名没挂上"的典型来源）。
 *
 * @param {ReadonlyArray<{serverName: string, transport: string, command?: string, args?: readonly string[], env?: Record<string, string>, cwd?: string, url?: string, headers?: Record<string, string>}>} servers
 * @param {{ header?: readonly string[] }} [options]
 */
export function renderMcpRows(servers, options = {}) {
	const lines = [...(options.header ?? DEFAULT_ROWS_HEADER)];
	if (servers.length) {
		lines.push('- insert:');
		for (const server of servers) {
			lines.push(`    - id: ${mcpRowId(server.serverName)}`);
			lines.push("      name: '@deepseek-ai/dsh-mcp-client'");
			lines.push('      config:');
			lines.push(`        serverName: ${yamlScalar(server.serverName)}`);
			lines.push(`        transport: ${yamlScalar(server.transport)}`);
			if (server.transport === 'stdio') {
				lines.push(`        command: ${yamlScalar(server.command ?? '')}`);
				if (server.args?.length) {
					lines.push(`        args: ${yamlInlineList(server.args)}`);
				}
				if (server.env) {
					lines.push('        env:');
					for (const [key, value] of Object.entries(server.env)) {
						lines.push(`          ${key}: ${yamlScalar(value)}`);
					}
				}
				if (server.cwd) {
					lines.push(`        cwd: ${yamlScalar(server.cwd)}`);
				}
			} else {
				lines.push(`        url: ${yamlScalar(server.url ?? '')}`);
				if (server.headers) {
					lines.push('        headers:');
					for (const [key, value] of Object.entries(server.headers)) {
						lines.push(`          ${key}: ${yamlScalar(value)}`);
					}
				}
			}
		}
	}
	lines.push('');
	return lines.join('\n');
}
