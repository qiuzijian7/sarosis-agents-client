#!/usr/bin/env node
// @vssaros/dsh-mcp — dsh 侧 CLI：读配置 → 渲染组合行 → **交给 loader**（全程不需要 VsSaros）。
//
// 用法（任意 cwd）：
//     node dsh-plugins/vssaros-mcp/bin/sync-rows.mjs [--config <mcp.json>] [--profile vssaros]
//                                                    [--dsh-bin <dsh 的 lib/bin.js>] [--patch-only <rows.yml>]
//
// 两种交付方式：
//   · **默认（bundle 模式）**：把行写成一个**独立的 bundle 包**，再用**官方** `dsh plugin add file:<dir>`
//     安装 + 登记到 profile 的 `dsh.profile.bundles` ⇒ 之后**直接起 Host 就生效**，无需任何 `--patch` ✓。
//     幂等与纪律（这是"动别人地盘"的代价，必须守住）：
//       ① 只在**行内容变化**时 bump 补丁版本（`dsh plugin add` 版本未变时是 no-op ⇒ 不 bump 就刷不进去 ✗）；
//       ② **只在自己的行/包里写**，绝不碰 `dsh.profile.bundles` 里别人的条目（该动作由官方 CLI 追加，我们不自写 ✗）；
//       ③ 重复跑安全：内容不变 ⇒ 版本不变 ⇒ CLI no-op ✓。
//     生效时机：**下次启动**（dsh 原生口径，与今天一致）。
//   · `--patch-only <file>`：只写行文件（老行为，便于 `--patch` 或自查）——不碰 profile ✓。
//
// 配置路径解析与插件本体**同一优先级**（`lib/index.js` 的 `mcpPathOf`）：
//     `--config` → `VSSAROS_DATA_ROOT`（拼 `mcp.json`）→ `~/.vssaros`。
//
// 退出码：0 已交付（含"跳过若干"）；2 配置读不了 / 没有可用服务器（不写空包掩盖问题 ✗）。
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { dirname, join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { parseMcpServers } from '../lib/core/mcpConfig.js';
import { renderMcpRows } from '../lib/core/mcpRows.js';

const argv = process.argv.slice(2);
const argOf = name => {
	const i = argv.indexOf(`--${name}`);
	return i >= 0 ? argv[i + 1] : undefined;
};

/** 配置路径：与插件同口径（`--config` 最高 → 数据根 → `~/.vssaros`）。 */
function configPathOf() {
	const explicit = argOf('config');
	if (explicit) { return explicit; }
	const envRoot = typeof process.env.VSSAROS_DATA_ROOT === 'string' ? process.env.VSSAROS_DATA_ROOT.trim() : '';
	if (envRoot) { return join(envRoot, 'mcp.json'); }
	const home = process.env.USERPROFILE || process.env.HOME || homedir();
	return join(home, '.vssaros', 'mcp.json');
}

function dshHomeOf() {
	const fromEnv = typeof process.env.DSH_HOME === 'string' ? process.env.DSH_HOME.trim() : '';
	return fromEnv || join(homedir(), '.dsh');
}

/** 补丁版本 +1（0.0.3 → 0.0.4）；解析不了就从 0.0.1 起。 */
function bumpPatch(version) {
	const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(version ?? ''));
	if (!m) { return '0.0.1'; }
	return `${m[1]}.${m[2]}.${Number(m[3]) + 1}`;
}

const configPath = configPathOf();
if (!existsSync(configPath)) {
	console.error(`没有 MCP 配置文件：${configPath}`);
	console.error('（这是常态——没配 MCP 的人不需要这一步；要生成请先建这个文件）');
	process.exit(2);
}

let parsed;
try {
	parsed = parseMcpServers(readFileSync(configPath, 'utf8'), process.env);
} catch (e) {
	console.error(`读不了 MCP 配置：${configPath} —— ${String(e?.message ?? e)}`);
	process.exit(2);
}

// 跳过项**必须报出来**：`sse` / 残留 `${...}` 是"配了但没挂上"的常见原因，静默跳过会让人以为配好了 ✗
for (const item of parsed.skipped) {
	console.warn(`跳过 ${item.name}：${item.reason}`);
}
if (!parsed.servers.length) {
	console.error(`没有可挂载的服务器（${configPath}；跳过 ${parsed.skipped.length} 个）。不写空包，免得掩盖问题。`);
	process.exit(2);
}

const rowsText = renderMcpRows(parsed.servers);

// ── 方式一：只写行文件（`--patch-only`；`--out` 是它的旧名，保留为别名，别打断既有调用 ✗）──
const patchOnly = argOf('patch-only') ?? argOf('out');
if (patchOnly) {
	mkdirSync(dirname(patchOnly), { recursive: true });
	writeFileSync(patchOnly, rowsText, 'utf8');
	console.log(`已生成 ${parsed.servers.length} 台服务器的组合行 → ${patchOnly}`);
	console.log(`（跳过 ${parsed.skipped.length} 个；交给 loader：dsh --patch "${patchOnly}" ...）`);
	process.exit(0);
}

// ── 方式二（默认）：作为独立 bundle 包交给官方 CLI 安装 + 登记 ──
const dshHome = dshHomeOf();
const profile = argOf('profile') ?? 'vssaros';
const bundleDir = join(dshHome, 'vssaros-mcp-bundle');
const bundlePkgPath = join(bundleDir, 'package.json');
const bundleRowsPath = join(bundleDir, 'cordis.patch.yml');

const prevRows = existsSync(bundleRowsPath) ? readFileSync(bundleRowsPath, 'utf8') : '';
const prevPkg = existsSync(bundlePkgPath) ? JSON.parse(readFileSync(bundlePkgPath, 'utf8')) : {};
const changed = prevRows !== rowsText;
const version = changed ? bumpPatch(prevPkg.version) : (prevPkg.version ?? '0.0.1');

mkdirSync(bundleDir, { recursive: true });
if (changed) {
	writeFileSync(bundleRowsPath, rowsText, 'utf8');
	writeFileSync(bundlePkgPath, `${JSON.stringify({
		name: '@vssaros/dsh-mcp-rows',
		version,
		private: true,
		description: 'Generated by @vssaros/dsh-mcp/bin/sync-rows.mjs: one @deepseek-ai/dsh-mcp-client row per configured MCP server. Regenerated from the configured mcp.json; safe to delete.',
		dsh: { bundle: { patch: ['./cordis.patch.yml'] } },
	}, null, 2)}\n`, 'utf8');
}

// 官方 CLI：安装 + 追加 `dsh.profile.bundles`（不重复）。版本未变时它是 no-op ⇒ 上面必须 bump ✓
const dshBin = argOf('dsh-bin') ?? process.env.VSSAROS_DSH_BIN ?? 'dsh';
const spec = `file:${bundleDir.replace(/\\/g, '/')}`;
const add = spawnSync(dshBin === 'dsh' ? 'dsh' : process.execPath, [
	...(dshBin === 'dsh' ? [] : [dshBin]),
	'plugin', '--profile', profile, 'add', spec,
], { encoding: 'utf8', env: { ...process.env, DSH_HOME: dshHome }, timeout: 180_000, shell: dshBin === 'dsh', windowsHide: true });

if (add.status !== 0) {
	console.error(`登记失败（dsh plugin add，exit=${add.status}）：${String(add.stdout ?? '').trim()} ${String(add.stderr ?? '').trim()}`);
	process.exit(2);
}

console.log(`已生成 ${parsed.servers.length} 台服务器的组合行 → ${bundleDir}（跳过 ${parsed.skipped.length} 个）`);
console.log(changed
	? `包版本 → ${version}，已用官方 CLI 安装并登记到 profile「${profile}」的 bundles（下次启动生效）`
	: `行内容未变 ⇒ 版本仍为 ${version}，官方 CLI 是 no-op（无需重启）`);
