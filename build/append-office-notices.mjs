/**
 * 把随包分发的**第三方许可正文**追加进 `ThirdPartyNotices.txt`（幂等：重跑替换同一段）。
 *
 * 为什么必须有这一步：Office 全量路线（2026-11-02）让安装包开始携带两份第三方二进制 ——
 *   · **Python 3.12.x**（PSF License）：`<appPath>/office-runtime/primary-runtime/dependencies/python/`
 *   · **LibreOffice Kit**（MPL-2.0）：`<appPath>/dsh-runtime/<ver>/node_modules/@deepseek-ai/libreoffice-kit-win32-x64/`
 * 两份包内**各自**已经带了许可文件（`python/LICENSE.txt`、`licenses/LibreOffice-MPL-2.0.txt`），
 * 但用户/法务实际会查的是产品级的 `ThirdPartyNotices.txt`（安装包根目录，VS Code 惯例）——
 * 那里此前没有它们 ⇒ 表面看是"分发了却没有声明"。
 *
 * 为什么从**真源文件**读许可正文而不是抄一份：许可正文与随包二进制必须同一版本同一份。
 * 抄一份 ⇒ 换 Python / LibreOffice 版本后两份文本静默分叉（而这正是合规审查最在意的东西 ✗）。
 *
 * 用法：node build/append-office-notices.mjs [--notices <file>] [--runtime <dsh-runtime 根>]
 * 顺序要求：先跑 `node build/prepare-office-runtime.mjs`（Python 的 LICENSE.txt 在那里）。
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');

const args = process.argv.slice(2);
const option = (name, fallback) => {
	const index = args.indexOf(name);
	return index >= 0 && args[index + 1] ? args[index + 1] : fallback;
};

const noticesPath = resolve(option('--notices', join(ROOT, 'ThirdPartyNotices.txt')));
const runtimeRoot = resolve(option('--runtime', join(ROOT, 'dsh-runtime', bundledVersion())));

/** 本仓内置的 dsh 版本（与 supervisor / 打包脚本同源）。 */
function bundledVersion() {
	try {
		const manifest = JSON.parse(readFileSync(join(ROOT, 'dsh-plugins', 'dsh-compat.json'), 'utf8'));
		return String(manifest.bundled ?? '').trim();
	} catch {
		return '';
	}
}

const SEPARATOR = '---------------------------------------------------------';
const MARKER = 'VsSaros Office runtime notices (generated by build/append-office-notices.mjs)';

const pythonLicense = join(ROOT, '.build', 'office-runtime', 'primary-runtime', 'dependencies', 'python', 'LICENSE.txt');
const libKitDir = join(runtimeRoot, 'node_modules', '@deepseek-ai', 'libreoffice-kit-win32-x64');
const libLicense = join(libKitDir, 'licenses', 'LibreOffice-MPL-2.0.txt');

if (!existsSync(pythonLicense)) {
	console.error(`[office-notices] 缺 Python 许可：${pythonLicense}\n  ⇒ 先跑 node build/prepare-office-runtime.mjs`);
	process.exit(1);
}
if (!existsSync(libLicense)) {
	console.error(`[office-notices] 缺 LibreOffice 许可：${libLicense}\n  ⇒ 检查 dsh-runtime 是否完整（--runtime 可指定）`);
	process.exit(1);
}

function kitVersion() {
	try {
		return JSON.parse(readFileSync(join(libKitDir, 'package.json'), 'utf8')).version ?? '';
	} catch {
		return '';
	}
}

function pythonVersion() {
	try {
		return JSON.parse(readFileSync(join(ROOT, '.build', 'office-runtime', 'primary-runtime', 'runtime.json'), 'utf8')).python ?? '';
	} catch {
		return '';
	}
}

const entries = [
	{
		name: `Python ${pythonVersion()}`.trim(),
		url: 'https://www.python.org/',
		body: readFileSync(pythonLicense, 'utf8').trim(),
	},
	{
		// 包版本是 kit 的（如 0.1.5），不是 LibreOffice 引擎版本 —— 引擎未随包带版本文件，
		// 所以这里照实写"kit 版本 + 随包引擎"，不编一个引擎版本号（写错比不写更糟）。
		name: `LibreOffice（libreoffice-kit ${kitVersion()} 随包引擎）`.trim(),
		url: 'https://www.libreoffice.org/',
		body: readFileSync(libLicense, 'utf8').trim(),
	},
];

const block = [
	'',
	`# ${MARKER}`,
	...entries.flatMap(entry => [
		'',
		SEPARATOR,
		'',
		entry.name,
		entry.url,
		'',
		entry.body,
	]),
	'',
].join('\n');

const original = readFileSync(noticesPath, 'utf8');
const markerAt = original.indexOf(`# ${MARKER}`);
// 幂等：标记之后的内容整段替换（同一段重跑不重复追加，升级版本时跟着更新）
const base = (markerAt >= 0 ? original.slice(0, markerAt) : original).replace(/\s*$/, '');
const eol = original.includes('\r\n') ? '\r\n' : '\n';
const next = `${base}${block.replace(/\n/g, eol)}`;

writeFileSync(noticesPath, next, 'utf8');
console.log(`[office-notices] ✓ ${noticesPath.replace(ROOT, '<repo>')}：+${entries.map(e => e.name).join(' / ')}（${(block.length / 1024).toFixed(1)} KB）`);
